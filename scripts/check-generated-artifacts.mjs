import { mkdir, mkdtemp, readFile, rm } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

import { build } from "esbuild";

import { readPluginSkillArtifacts } from "./build-plugin-skills.mjs";

const repositoryRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const bundleDefinitions = [
  ["plugins/claude-code/mcp/server.bundle.mjs", "plugins/claude-code/mcp/server.mjs", "scripts/build-claude-plugin.mjs"],
  ["plugins/claude-code/scripts/progress-reminder.bundle.mjs", "scripts/progress-reminder.mjs", "scripts/build-claude-plugin.mjs"],
  ["plugins/claude-code/scripts/rename-session.bundle.mjs", "plugins/claude-code/scripts/rename-session.mjs", "scripts/build-claude-plugin.mjs"],
  ["plugins/pomegr/mcp/server.bundle.mjs", "mcp/server.mjs", "scripts/build-codex-plugin.mjs"],
  ["plugins/pomegr/scripts/progress-reminder.bundle.mjs", "scripts/progress-reminder.mjs", "scripts/build-codex-plugin.mjs"],
  ["plugins/pomegr/scripts/codex-lifecycle-bridge.bundle.mjs", "scripts/codex-plugin-lifecycle-bridge.mjs", "scripts/build-codex-plugin.mjs"],
  ["plugins/pomegr/scripts/codex-lifecycle-owner.bundle.mjs", "scripts/codex-lifecycle-owner.mjs", "scripts/build-codex-plugin.mjs"],
];
const buildOptions = {
  bundle: true,
  platform: "node",
  format: "esm",
  target: "node22",
  minify: true,
  legalComments: "eof",
};

async function compareFile(relativePath, expected) {
  const absolutePath = path.join(repositoryRoot, relativePath);
  let actual;
  try {
    actual = await readFile(absolutePath, "utf8");
  } catch {
    return `${relativePath} is missing`;
  }
  return actual === expected ? null : `${relativePath} is out of sync with its source`;
}

const errors = [];
for (const provider of ["claude", "codex"]) {
  for (const artifact of await readPluginSkillArtifacts(provider)) {
    const relativePath = path.relative(repositoryRoot, artifact.outputFile).split(path.sep).join("/");
    const error = await compareFile(relativePath, artifact.content);
    if (error) errors.push(error);
  }
}

for (const [outputFile, sourceFile] of [
  ["plugins/pomegr/hooks/hooks.json", "plugin-src/codex-hooks.json"],
]) {
  const error = await compareFile(outputFile, await readFile(path.join(repositoryRoot, sourceFile), "utf8"));
  if (error) errors.push(error);
}

// The managed Windows sandbox may deny the system temp directory. Keep this
// short-lived workspace inside the repository and remove it in the finally block.
const temporaryRoot = await mkdtemp(path.join(repositoryRoot, ".generated-check-"));
try {
  for (const [outputFile, entryPoint, builder] of bundleDefinitions) {
    const temporaryOutput = path.join(temporaryRoot, outputFile);
    await mkdir(path.dirname(temporaryOutput), { recursive: true });
    await build({
      ...buildOptions,
      entryPoints: [path.join(repositoryRoot, entryPoint)],
      outfile: temporaryOutput,
      banner: { js: `// Generated by ${builder}. Do not edit directly.` },
    });
    let expected = await readFile(temporaryOutput, "utf8");
    if (outputFile.startsWith("plugins/pomegr/")) expected = expected.replace(/[\t ]+$/gm, "");
    const error = await compareFile(outputFile, expected);
    if (error) errors.push(error);
  }
} finally {
  await rm(temporaryRoot, { recursive: true, force: true });
}

if (errors.length) {
  console.error("Generated artifact checks failed:");
  for (const error of errors) console.error(`- ${error}`);
  process.exitCode = 1;
} else {
  console.log(`Generated artifact checks passed (${bundleDefinitions.length} bundles and rendered skills).`);
}
