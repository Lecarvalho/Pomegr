import { mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const repositoryRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const skillSourceRoot = path.join(repositoryRoot, "plugin-src", "skills");

export const GENERATED_SKILL_NOTICE = "<!-- Generated by scripts/build-plugin-skills.mjs from plugin-src/skills. Do not edit directly. -->";

const PROVIDERS = {
  codex: path.join(repositoryRoot, "plugins", "pomegr"),
  claude: path.join(repositoryRoot, "plugins", "claude-code"),
};

const SKILL_NAMES = ["init", "doctor"];
const CONDITIONAL_PATTERN = /\{\{#(codex|claude)\}\}([\s\S]*?)\{\{\/\1\}\}/g;
const UNRESOLVED_DIRECTIVE_PATTERN = /\{\{\/?(?:codex|claude)\}\}/;

function normalizeText(value) {
  return `${value.replace(/\r\n?/g, "\n").replace(/[\t ]+$/gm, "").trimEnd()}\n`;
}

export function renderProviderSkill(source, provider) {
  if (!Object.hasOwn(PROVIDERS, provider)) throw new Error(`Unsupported plugin skill provider: ${provider}`);
  const rendered = source.replace(CONDITIONAL_PATTERN, (_match, blockProvider, content) => blockProvider === provider ? content : "");
  if (UNRESOLVED_DIRECTIVE_PATTERN.test(rendered)) throw new Error(`Unresolved plugin skill directive for ${provider}`);
  const frontmatter = rendered.match(/^---\r?\n[\s\S]*?\r?\n---\r?\n/);
  if (!frontmatter) throw new Error(`Plugin skill template for ${provider} has invalid frontmatter`);
  return normalizeText(`${frontmatter[0]}\n${GENERATED_SKILL_NOTICE}\n${rendered.slice(frontmatter[0].length)}`);
}

export async function readPluginSkillArtifacts(provider) {
  const pluginRoot = PROVIDERS[provider];
  if (!pluginRoot) throw new Error(`Unsupported plugin skill provider: ${provider}`);
  const artifacts = [];
  for (const skillName of SKILL_NAMES) {
    const sourceFile = path.join(skillSourceRoot, skillName, "SKILL.md.tmpl");
    const outputFile = path.join(pluginRoot, "skills", skillName, "SKILL.md");
    artifacts.push({ sourceFile, outputFile, content: renderProviderSkill(await readFile(sourceFile, "utf8"), provider) });
  }
  const policySource = path.join(skillSourceRoot, "init", "references", "policy-template.md");
  const policyOutput = path.join(pluginRoot, "skills", "init", "references", "policy-template.md");
  artifacts.push({ sourceFile: policySource, outputFile: policyOutput, content: normalizeText(await readFile(policySource, "utf8")) });
  return artifacts;
}

export async function buildPluginSkills(providers = Object.keys(PROVIDERS)) {
  const outputs = [];
  for (const provider of providers) {
    for (const artifact of await readPluginSkillArtifacts(provider)) {
      await mkdir(path.dirname(artifact.outputFile), { recursive: true });
      await writeFile(artifact.outputFile, artifact.content, "utf8");
      outputs.push(artifact.outputFile);
    }
  }
  return outputs;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const requested = process.argv.slice(2);
  const providers = !requested.length || requested.includes("all") ? Object.keys(PROVIDERS) : requested;
  const outputs = await buildPluginSkills(providers);
  for (const output of outputs) console.log(`Pomegr plugin skill: ${path.relative(repositoryRoot, output)}`);
}
