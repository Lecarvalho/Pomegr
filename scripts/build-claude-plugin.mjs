import { mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

import { build } from "esbuild";

import { buildPluginSkills } from "./build-plugin-skills.mjs";

const repositoryRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const pluginRoot = path.join(repositoryRoot, "plugins", "claude-code");
const hooksSourceFile = path.join(repositoryRoot, "plugin-src", "claude-hooks.json");
const hooksOutputFile = path.join(pluginRoot, "hooks", "hooks.json");
const bundles = [
  {
    entryPoint: path.join(repositoryRoot, "plugin-src", "claude-query-session.mjs"),
    outputFile: path.join(pluginRoot, "scripts", "query-session.bundle.mjs"),
  },
  {
    entryPoint: path.join(pluginRoot, "mcp", "server.mjs"),
    outputFile: path.join(pluginRoot, "mcp", "server.bundle.mjs"),
  },
  {
    entryPoint: path.join(pluginRoot, "scripts", "rename-session.mjs"),
    outputFile: path.join(pluginRoot, "scripts", "rename-session.bundle.mjs"),
  },
  {
    entryPoint: path.join(repositoryRoot, "scripts", "progress-reminder.mjs"),
    outputFile: path.join(pluginRoot, "scripts", "progress-reminder.bundle.mjs"),
  },
  {
    entryPoint: path.join(repositoryRoot, "scripts", "usage-guard.mjs"),
    outputFile: path.join(pluginRoot, "scripts", "usage-guard.bundle.mjs"),
  },
];

export async function buildClaudePluginMcp() {
  const skillFiles = await buildPluginSkills(["claude"]);
  for (const bundle of bundles) {
    await mkdir(path.dirname(bundle.outputFile), { recursive: true });
    await build({
      entryPoints: [bundle.entryPoint],
      outfile: bundle.outputFile,
      bundle: true,
      platform: "node",
      format: "esm",
      target: "node22",
      minify: true,
      legalComments: "eof",
      banner: {
        js: "// Generated by scripts/build-claude-plugin.mjs. Do not edit directly.",
      },
    });
  }
  await mkdir(path.dirname(hooksOutputFile), { recursive: true });
  await writeFile(hooksOutputFile, await readFile(hooksSourceFile, "utf8"), "utf8");
  return [...skillFiles, ...bundles.map((bundle) => bundle.outputFile), hooksOutputFile];
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const built = await buildClaudePluginMcp();
  for (const file of built) console.log(`Pomegr Claude plugin artifact: ${path.relative(repositoryRoot, file)}`);
}
