import { mkdir } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

import { build } from "esbuild";

const repositoryRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const pluginRoot = path.join(repositoryRoot, "plugins", "claude-code");
const entryPoint = path.join(pluginRoot, "mcp", "server.mjs");
const outputFile = path.join(pluginRoot, "mcp", "server.bundle.mjs");

export async function buildClaudePluginMcp() {
  await mkdir(path.dirname(outputFile), { recursive: true });
  await build({
    entryPoints: [entryPoint],
    outfile: outputFile,
    bundle: true,
    platform: "node",
    format: "esm",
    target: "node22",
    minify: true,
    legalComments: "eof",
    banner: {
      js: "// Generated by scripts/build-claude-plugin.mjs. Do not edit directly.",
    },
  });
  return outputFile;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const built = await buildClaudePluginMcp();
  console.log(`Pomegr Claude plugin MCP bundle: ${path.relative(repositoryRoot, built)}`);
}
