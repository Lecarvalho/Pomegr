import { mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

import { build } from "esbuild";

import { buildPluginSkills } from "./build-plugin-skills.mjs";

const repositoryRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const entryPoint = path.join(repositoryRoot, "mcp", "server.mjs");
const outputFile = path.join(repositoryRoot, "plugins", "pomegr", "mcp", "server.bundle.mjs");
const reminderEntryPoint = path.join(repositoryRoot, "scripts", "progress-reminder.mjs");
const reminderOutputFile = path.join(repositoryRoot, "plugins", "pomegr", "scripts", "progress-reminder.bundle.mjs");
const lifecycleBridgeEntryPoint = path.join(repositoryRoot, "scripts", "codex-plugin-lifecycle-bridge.mjs");
const lifecycleBridgeOutputFile = path.join(repositoryRoot, "plugins", "pomegr", "scripts", "codex-lifecycle-bridge.bundle.mjs");
const lifecycleOwnerEntryPoint = path.join(repositoryRoot, "scripts", "codex-lifecycle-owner.mjs");
const lifecycleOwnerOutputFile = path.join(repositoryRoot, "plugins", "pomegr", "scripts", "codex-lifecycle-owner.bundle.mjs");
const hooksSourceFile = path.join(repositoryRoot, "plugin-src", "codex-hooks.json");
const hooksOutputFile = path.join(repositoryRoot, "plugins", "pomegr", "hooks", "hooks.json");

async function buildBundle(entryPoint, outfile) {
  await mkdir(path.dirname(outfile), { recursive: true });
  await build({
    entryPoints: [entryPoint],
    outfile,
    bundle: true,
    platform: "node",
    format: "esm",
    target: "node22",
    minify: true,
    legalComments: "eof",
    banner: {
      js: "// Generated by scripts/build-codex-plugin.mjs. Do not edit directly.",
    },
  });
  const bundledSource = await readFile(outfile, "utf8");
  await writeFile(outfile, bundledSource.replace(/[\t ]+$/gm, ""), "utf8");
}

export async function buildCodexPluginMcp() {
  const skillFiles = await buildPluginSkills(["codex"]);
  await Promise.all([
    buildBundle(entryPoint, outputFile),
    buildBundle(reminderEntryPoint, reminderOutputFile),
    buildBundle(lifecycleBridgeEntryPoint, lifecycleBridgeOutputFile),
    buildBundle(lifecycleOwnerEntryPoint, lifecycleOwnerOutputFile),
  ]);
  await mkdir(path.dirname(hooksOutputFile), { recursive: true });
  await writeFile(hooksOutputFile, await readFile(hooksSourceFile, "utf8"), "utf8");
  return [...skillFiles, outputFile, reminderOutputFile, lifecycleBridgeOutputFile, lifecycleOwnerOutputFile, hooksOutputFile];
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const built = await buildCodexPluginMcp();
  for (const file of built) console.log(`Pomegr Codex plugin artifact: ${path.relative(repositoryRoot, file)}`);
}
