import { mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

import { build } from "esbuild";

import { buildPluginSkills } from "./build-plugin-skills.mjs";

const repositoryRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const entryPoint = path.join(repositoryRoot, "mcp", "server.mjs");
const outputFile = path.join(repositoryRoot, "plugins", "pomegr", "mcp", "server.bundle.mjs");
const reminderEntryPoint = path.join(repositoryRoot, "scripts", "progress-reminder.mjs");
const reminderOutputFile = path.join(repositoryRoot, "plugins", "pomegr", "scripts", "progress-reminder.bundle.mjs");

export async function buildCodexPluginMcp() {
  const skillFiles = await buildPluginSkills(["codex"]);
  await mkdir(path.dirname(outputFile), { recursive: true });
  await build({
    entryPoints: [entryPoint],
    outfile: outputFile,
    bundle: true,
    platform: "node",
    format: "esm",
    target: "node22",
    minify: true,
    legalComments: "eof",
    banner: {
      js: "// Generated by scripts/build-codex-plugin.mjs. Do not edit directly.",
    },
  });
  const bundledSource = await readFile(outputFile, "utf8");
  await writeFile(outputFile, bundledSource.replace(/[\t ]+$/gm, ""), "utf8");
  await mkdir(path.dirname(reminderOutputFile), { recursive: true });
  await build({
    entryPoints: [reminderEntryPoint],
    outfile: reminderOutputFile,
    bundle: true,
    platform: "node",
    format: "esm",
    target: "node22",
    minify: true,
    legalComments: "eof",
    banner: {
      js: "// Generated by scripts/build-codex-plugin.mjs. Do not edit directly.",
    },
  });
  return [...skillFiles, outputFile, reminderOutputFile];
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const built = await buildCodexPluginMcp();
  for (const file of built) console.log(`Pomegr Codex plugin artifact: ${path.relative(repositoryRoot, file)}`);
}
